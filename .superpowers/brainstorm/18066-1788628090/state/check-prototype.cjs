const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const html = fs.readFileSync(path.join(__dirname, '../content/ios-mac-handoff.html'), 'utf8');
const scripts = [...html.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/g)].map(m => m[1]);
for (const source of scripts) new vm.Script(source);
const context = vm.createContext({});
vm.runInContext(scripts[0], context);
let s = context.initialState();
assert.equal(context.transition(s, 'submit').job, 'idle', 'Offline submission must be blocked');
s = context.transition(s, 'connect');
s = context.transition(s, 'detail');
s = context.transition(s, 'submit');
assert.equal(s.job, 'sending');
assert.equal(s.jobScope, 'analysis');
assert.equal(context.transition(s, 'submit').job, 'sending', 'Repeated submission cannot restart job');
s = context.transition(s, 'toggleConnection');
assert.equal(context.transition(s, 'next').job, 'sending', 'Offline send must wait');
s = context.transition(s, 'connect');
s = context.transition(s, 'next');
assert.equal(s.job, 'accepted');
s = context.transition(s, 'toggleConnection');
s = context.transition(s, 'home');
s = context.transition(s, 'next');
assert.equal(s.job, 'processing', 'Accepted Mac task survives disconnect and navigation');
s = context.transition(s, 'next');
assert.equal(s.job, 'done');
assert.equal(s.page, 'home');
assert.equal(s.connected, false);
assert.equal(context.transition(s, 'submit').job, 'done');
assert.ok(html.includes('role="dialog"'));
assert.ok(html.includes('aria-label="返回会议列表"'));
console.log('PASS: script syntax; offline guard; submission deduplication; receipt; background completion; navigation; accessible controls.');
